//! Declarative timelines and deterministic shader-constant sampling.

use std::fmt;

use super::super::Result;

/// Maximum generated preview period; native clocks can describe much longer loops.
const MAX_PERIOD_MS: u32 = 120_000;

/// Why captured animation code cannot be evaluated by the supported patterns.
#[derive(Debug)]
pub(crate) enum Error {
    /// The method contains behavior outside the bounded animation recognizer.
    Unsupported {
        /// Fully qualified method or field being inspected.
        context: String,
        /// Instruction byte offset, where the unsupported behavior was found.
        offset: Option<u32>,
        /// Specific operation or missing metadata that prevented extraction.
        detail: String,
    },
    /// Extracted data cannot describe a finite, valid animation.
    Invalid(String),
}

impl fmt::Display for Error {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unsupported {
                context,
                offset,
                detail,
            } => {
                // Report the original method and IL offset alongside the unsupported operation.
                write!(formatter, "unsupported animation pattern in {context}")?;
                if let Some(offset) = offset {
                    write!(formatter, " at IL_{offset:04x}")?;
                }
                write!(formatter, ": {detail}")
            }
            Self::Invalid(detail) => write!(formatter, "invalid extracted animation: {detail}"),
        }
    }
}

impl std::error::Error for Error {}

/// Interpolation applied between the preceding value and one destination keyframe.
#[derive(Debug, Clone, Copy, PartialEq)]
pub(crate) enum Interpolation {
    /// Uniform interpolation over the keyframe interval.
    Linear,
    /// Retain the preceding value until the destination key time.
    Discrete,
    /// Sinusoidal acceleration from the previous value.
    SineIn,
    /// Sinusoidal deceleration toward the destination value.
    SineOut,
    /// Symmetric sinusoidal acceleration and deceleration.
    SineInOut,
}

impl Interpolation {
    /// Convert a normalized interval fraction into the destination's easing fraction.
    fn ease(self, fraction: f64) -> f64 {
        match self {
            Self::Linear => fraction,
            Self::Discrete => {
                if fraction >= 1.0 {
                    1.0
                } else {
                    0.0
                }
            }
            Self::SineIn => 1.0 - (fraction * std::f64::consts::FRAC_PI_2).cos(),
            Self::SineOut => (fraction * std::f64::consts::FRAC_PI_2).sin(),
            Self::SineInOut => 0.5 - 0.5 * (fraction * std::f64::consts::PI).cos(),
        }
    }
}

/// One value and interpolation mode read from a WPF keyframe constructor.
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct Keyframe {
    /// Elapsed seconds on the timeline, before repeat or reverse behavior.
    pub(crate) seconds: f64,
    /// Scalar value at that elapsed time.
    pub(crate) value: f64,
    /// Interpolation used to approach this keyframe.
    pub(crate) interpolation: Interpolation,
}

/// Scalar values generated by one supported timeline.
#[derive(Debug, Clone, PartialEq)]
pub(crate) enum Curve {
    /// Linear range used by DoubleAnimation and IntervalDoubleAnimation.
    Range {
        /// Range value before progression begins.
        from: f64,
        /// Range value after one forward iteration.
        to: f64,
    },
    /// Explicit discrete, linear, or easing keyframes.
    Keyframes(Vec<Keyframe>),
}

/// Declarative animation data recovered from a client method or static field.
#[derive(Debug, Clone, PartialEq)]
pub(crate) struct Timeline {
    /// Values and local interpolation behavior.
    pub(crate) curve: Curve,
    /// Duration in seconds of one forward iteration.
    pub(crate) duration: f64,
    /// Whether the animation restarts after its forward/reverse cycle.
    pub(crate) repeat: bool,
    /// Whether each forward iteration is followed by a reverse iteration.
    pub(crate) auto_reverse: bool,
    /// Fraction of the forward duration spent accelerating.
    pub(crate) acceleration: f64,
    /// Fraction of the forward duration spent decelerating.
    pub(crate) deceleration: f64,
}

impl Timeline {
    /// Reject nonfinite values, reversed key times, and invalid timing parameters.
    pub(crate) fn validate(&self) -> Result<()> {
        if !self.duration.is_finite()
            || self.duration < 0.0
            || !self.acceleration.is_finite()
            || !self.deceleration.is_finite()
            || self.acceleration < 0.0
            || self.deceleration < 0.0
            || self.acceleration + self.deceleration > 1.0
        {
            return Err(Error::Invalid("duration or acceleration parameters".into()).into());
        }
        match &self.curve {
            Curve::Range { from, to } if from.is_finite() && to.is_finite() => {}
            Curve::Range { .. } => {
                return Err(Error::Invalid("nonfinite range value".into()).into());
            }
            Curve::Keyframes(frames) => {
                // Validate keyframe ordering and values before evaluating intervals or held tails.
                let mut previous = 0.0;
                for frame in frames {
                    if !frame.seconds.is_finite()
                        || !frame.value.is_finite()
                        || frame.seconds < previous
                        || frame.seconds > self.duration
                    {
                        return Err(Error::Invalid("keyframe value or time".into()).into());
                    }
                    previous = frame.seconds;
                }
                if frames.is_empty() {
                    return Err(Error::Invalid("empty keyframe animation".into()).into());
                }
            }
        }
        Ok(())
    }

    /// Full native repeat period including an optional return stroke.
    pub(crate) fn period_ms(&self) -> Result<u32> {
        self.validate()?;
        let milliseconds = self.duration * if self.auto_reverse { 2000.0 } else { 1000.0 };
        if milliseconds > f64::from(u32::MAX) {
            return Err(
                Error::Invalid("timeline period exceeds integer milliseconds".into()).into(),
            );
        }
        Ok(milliseconds.round() as u32)
    }

    /// Evaluate repeat, reverse, acceleration, and keyframe interpolation at elapsed seconds.
    pub(crate) fn sample(&self, seconds: f64) -> Result<f64> {
        self.validate()?;
        if !seconds.is_finite() || seconds < 0.0 {
            return Err(Error::Invalid("sample time must be finite and nonnegative".into()).into());
        }
        let cycle = self.duration * if self.auto_reverse { 2.0 } else { 1.0 };
        let mut elapsed = if self.repeat && cycle > 0.0 {
            seconds % cycle
        } else {
            seconds.min(cycle)
        };
        if self.auto_reverse && elapsed > self.duration {
            elapsed = cycle - elapsed;
        }
        let fraction = if self.duration == 0.0 {
            1.0
        } else {
            elapsed / self.duration
        };
        let rate = 1.0 / (1.0 - (self.acceleration + self.deceleration) / 2.0);
        let progress = if self.acceleration > 0.0 && fraction < self.acceleration {
            rate * fraction * fraction / (2.0 * self.acceleration)
        } else if self.deceleration > 0.0 && fraction > 1.0 - self.deceleration {
            1.0 - rate * (1.0 - fraction).powi(2) / (2.0 * self.deceleration)
        } else {
            rate * (fraction - self.acceleration / 2.0)
        };
        Ok(match &self.curve {
            Curve::Range { from, to } => from + (to - from) * progress,
            Curve::Keyframes(frames) => sample_keyframes(frames, progress * self.duration),
        })
    }

    /// Reproducible pointer position used by preview policy instead of native UI events.
    pub(crate) fn mouse_loop() -> Self {
        Self {
            curve: Curve::Keyframes(vec![
                Keyframe {
                    seconds: 0.0,
                    value: 0.0,
                    interpolation: Interpolation::Linear,
                },
                Keyframe {
                    seconds: 6.0,
                    value: 1.0,
                    interpolation: Interpolation::SineInOut,
                },
                Keyframe {
                    seconds: 12.0,
                    value: 0.0,
                    interpolation: Interpolation::SineInOut,
                },
            ]),
            duration: 12.0,
            repeat: true,
            auto_reverse: false,
            acceleration: 0.0,
            deceleration: 0.0,
        }
    }
}

/// Evaluate WPF keyframes, including duplicate times and held tails.
fn sample_keyframes(frames: &[Keyframe], seconds: f64) -> f64 {
    let mut previous_time = 0.0;
    let mut previous_value = 0.0;
    for frame in frames {
        // Use the destination frame's interpolation from the preceding frame's value.
        if seconds < frame.seconds {
            let fraction =
                ((seconds - previous_time) / (frame.seconds - previous_time)).clamp(0.0, 1.0);
            return previous_value
                + (frame.value - previous_value) * frame.interpolation.ease(fraction);
        }
        previous_time = frame.seconds;
        previous_value = frame.value;
    }
    previous_value
}

/// How an animated property updates the shader's float4 register contents.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Target {
    /// A scalar dependency property replaces its entire register with `[value, 1, 1, 1]`.
    Scalar(usize),
    /// A scalar alias updates one component of a vector dependency property.
    Component {
        /// Zero-based float4 register index.
        register: usize,
        /// Zero-based x/y/z/w component index.
        component: usize,
    },
}

/// A scalar animation and the property packing it applies to a shader register.
#[derive(Debug, Clone)]
pub(crate) struct Track {
    /// Complete-register scalar packing or one vector-component alias.
    pub(crate) target: Target,
    /// Timeline extracted for the dependency property controlling this component.
    pub(crate) timeline: Timeline,
}

/// Complete deterministic constants used by one extracted effect definition.
#[derive(Debug, Clone)]
pub(crate) struct Program {
    /// Captured default values, before animated scalar tracks are applied.
    defaults: Vec<[f32; 4]>,
    /// Supported animation and virtual-pointer tracks.
    tracks: Vec<Track>,
    /// Preview duration, after repeat cycles have been combined and bounded.
    period_ms: u32,
    /// Human-readable preview policy retained with the generated WebP.
    timing: String,
}

impl Program {
    /// Validate and combine the native periods of the provided tracks.
    pub(crate) fn new(defaults: Vec<[f32; 4]>, tracks: Vec<Track>, timing: String) -> Result<Self> {
        if defaults.iter().flatten().any(|value| !value.is_finite()) {
            return Err(Error::Invalid("nonfinite default registers".into()).into());
        }
        let mut period = 0_u32;
        let mut one_shot = 0_u32;
        for track in &tracks {
            // Validate targets before combining repeat cycles with one-shot durations.
            let (register, component) = match track.target {
                Target::Scalar(register) => (register, 0),
                Target::Component {
                    register,
                    component,
                } => (register, component),
            };
            if register >= defaults.len() || component >= 4 {
                return Err(Error::Invalid(
                    "animation targets an absent register component".into(),
                )
                .into());
            }
            let next = track.timeline.period_ms()?;
            if !track.timeline.repeat {
                one_shot = one_shot.max(next);
            } else if next > 0 {
                period = if period == 0 {
                    next
                } else {
                    let divisor = gcd(period, next);
                    period
                        .checked_div(divisor)
                        .and_then(|value| value.checked_mul(next))
                        .ok_or_else(|| {
                            Error::Invalid("combined animation period overflow".into())
                        })?
                };
            }
        }
        if period == 0 {
            period = one_shot.max(1000);
        } else if one_shot > period {
            period = one_shot
                .div_ceil(period)
                .checked_mul(period)
                .ok_or_else(|| Error::Invalid("combined animation period overflow".into()))?;
        }
        if period > MAX_PERIOD_MS {
            return Err(Error::Invalid(format!(
                "combined animation period {period}ms exceeds {MAX_PERIOD_MS}ms"
            ))
            .into());
        }
        Ok(Self {
            defaults,
            tracks,
            period_ms: period,
            timing,
        })
    }

    /// Number of float4 registers supplied to the translated shader.
    pub(crate) fn registers(&self) -> usize {
        self.defaults.len()
    }

    /// Exact preview cycle duration in integer milliseconds.
    pub(crate) fn period_ms(&self) -> u32 {
        self.period_ms
    }

    /// Description of extraction and deterministic interaction policy.
    pub(crate) fn timing(&self) -> &str {
        &self.timing
    }

    /// Sample all tracks without altering the captured default values.
    pub(crate) fn sample(&self, seconds: f64) -> Result<Vec<[f32; 4]>> {
        if !seconds.is_finite() || seconds < 0.0 {
            return Err(Error::Invalid("sample time must be finite and nonnegative".into()).into());
        }
        // The finished WebP retriggers one-shot transitions when its preview loop restarts.
        let seconds = seconds % (f64::from(self.period_ms) / 1000.0);
        let mut values = self.defaults.clone();
        for track in &self.tracks {
            // Apply register packing only after checking that the sampled value is representable.
            let value = track.timeline.sample(seconds)?;
            if !value.is_finite() || value.abs() > f64::from(f32::MAX) {
                return Err(Error::Invalid(
                    "animated constant is outside finite float range".into(),
                )
                .into());
            }
            match track.target {
                Target::Scalar(register) => values[register] = [value as f32, 1.0, 1.0, 1.0],
                Target::Component {
                    register,
                    component,
                } => values[register][component] = value as f32,
            }
        }
        Ok(values)
    }
}

/// Greatest common divisor used to combine native repeat periods exactly.
fn gcd(mut left: u32, mut right: u32) -> u32 {
    while right != 0 {
        (left, right) = (right, left % right);
    }
    left
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Keyframe holds, interpolation, reverse easing, and repeat boundaries affect playback.
    #[test]
    fn extracted_timelines_preserve_interpolation_and_complete_cycles() -> Result<()> {
        let keyframes = Timeline {
            curve: Curve::Keyframes(vec![
                Keyframe {
                    seconds: 0.5,
                    value: 0.0,
                    interpolation: Interpolation::Linear,
                },
                Keyframe {
                    seconds: 2.5,
                    value: 1.0,
                    interpolation: Interpolation::Linear,
                },
                Keyframe {
                    seconds: 5.5,
                    value: 1.0,
                    interpolation: Interpolation::Discrete,
                },
                Keyframe {
                    seconds: 7.5,
                    value: 0.0,
                    interpolation: Interpolation::Linear,
                },
                Keyframe {
                    seconds: 37.5,
                    value: 0.0,
                    interpolation: Interpolation::Linear,
                },
            ]),
            duration: 37.5,
            repeat: true,
            auto_reverse: false,
            acceleration: 0.0,
            deceleration: 0.0,
        };
        assert_eq!(keyframes.sample(1.5)?, 0.5);
        assert_eq!(keyframes.sample(5.0)?, 1.0);
        assert_eq!(keyframes.sample(7.5)?, 0.0);
        assert_eq!(keyframes.sample(37.5)?, keyframes.sample(0.0)?);
        let range = Timeline {
            curve: Curve::Range {
                from: 0.0,
                to: 30.0,
            },
            duration: 30.0,
            repeat: true,
            auto_reverse: true,
            acceleration: 0.25,
            deceleration: 0.25,
        };
        assert_eq!(range.sample(30.0)?, 30.0);
        assert_eq!(range.sample(15.0)?, range.sample(45.0)?);
        assert_eq!(range.sample(60.0)?, 0.0);
        assert!((range.sample(3.0)? - 0.8).abs() < 1e-12);
        let mouse = Timeline::mouse_loop();
        assert_eq!(mouse.sample(0.0)?, 0.0);
        assert_eq!(mouse.sample(6.0)?, 1.0);
        assert_eq!(mouse.sample(12.0)?, 0.0);
        assert!((mouse.sample(3.0)? - 0.5).abs() < 1e-12);
        let clock = Timeline {
            curve: Curve::Range {
                from: 0.0,
                to: 20.0,
            },
            duration: 20.0,
            repeat: false,
            auto_reverse: false,
            acceleration: 0.0,
            deceleration: 0.0,
        };
        let transition = Timeline {
            curve: Curve::Keyframes(vec![
                Keyframe {
                    seconds: 0.0,
                    value: 0.0,
                    interpolation: Interpolation::Discrete,
                },
                Keyframe {
                    seconds: 3.0,
                    value: 0.7,
                    interpolation: Interpolation::Linear,
                },
                Keyframe {
                    seconds: 9.0,
                    value: 0.0,
                    interpolation: Interpolation::Linear,
                },
            ]),
            duration: 9.0,
            repeat: false,
            auto_reverse: false,
            acceleration: 0.0,
            deceleration: 0.0,
        };
        let program = Program::new(
            vec![[0.0; 4]; 2],
            vec![
                Track {
                    target: Target::Scalar(0),
                    timeline: clock,
                },
                Track {
                    target: Target::Scalar(1),
                    timeline: transition,
                },
            ],
            "one-shot clock and held transition".into(),
        )?;
        assert_eq!(program.period_ms(), 20_000);
        assert_eq!(
            program.sample(15.0)?,
            vec![[15.0, 1.0, 1.0, 1.0], [0.0, 1.0, 1.0, 1.0]]
        );
        assert_eq!(program.sample(20.0)?, program.sample(0.0)?);
        let packed = Program::new(
            vec![[5.0, 6.0, 7.0, 8.0], [9.0, 10.0, 11.0, 12.0]],
            vec![
                Track {
                    target: Target::Scalar(0),
                    timeline: mouse.clone(),
                },
                Track {
                    target: Target::Component {
                        register: 1,
                        component: 1,
                    },
                    timeline: mouse,
                },
            ],
            "scalar register packing and a vector component alias".into(),
        )?;
        let values = packed.sample(3.0)?;
        assert!((values[0][0] - 0.5).abs() < 1e-6);
        assert_eq!(&values[0][1..], &[1.0, 1.0, 1.0]);
        assert!((values[1][1] - 0.5).abs() < 1e-6);
        assert_eq!(
            [values[1][0], values[1][2], values[1][3]],
            [9.0, 11.0, 12.0]
        );
        Ok(())
    }
}
